def entities(text):
    for block in text.split(';'):
        block = block.strip()
        if not block:
            continue
        head, _, body = block.partition('\n')
        f = [x.strip() for x in head.split(':')]
        if len(f) < 8:
            continue
        name, lat, lon = f[0], float(f[4]), -float(f[5])
        yield name, lat, lon, [p.strip() for p in body.replace('\n', ' ').split(',') if p.strip()]


groups = {}            # (lat10, lon10, name) -> prefixes
for name, lat, lon, prefixes in entities(open(sys.argv[1], encoding='latin-1').read()):
    for p in prefixes:
        if p.startswith('='):
            continue
        plat, plon = lat, lon
        m = re.search(r'<([-\d.]+)/([-\d.]+)>', p)
        if m:
            plat, plon = float(m.group(1)), -float(m.group(2))
        call = re.sub(r'\(.*?\)|\[.*?\]|<.*?>|\{.*?\}|~.*?~', '', p).strip()
        if not re.fullmatch(r'[A-Z0-9/]+', call):
            continue
        key = (round(plat * 10), round(plon * 10), name.replace(':', ' ').replace(';', ' '))
        groups.setdefault(key, []).append(call)

print('// Generated by utils/map_prefixes.py from AD1C\'s cty.dat.')
for line in NOTICE.splitlines():
    print('// ' + line)
print('// Country per callsign prefix: "lat,lon,name:PREFIX ...", tenths of a degree.')
print('var MAP_PREFIXES = "%s";' % ';'.join(
    '%d,%d,%s:%s' % (k[0], k[1], k[2], ' '.join(sorted(set(v)))) for k, v in sorted(groups.items(), key=lambda kv: kv[0][2])))
