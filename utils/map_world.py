#!/usr/bin/env python3
"""Write gui_interface/web/map-world.js, the coastlines and borders map.html draws.

Natural Earth 1:110m land and land boundary lines (public domain,
https://www.naturalearthdata.com), from the natural-earth-vector repository:

    T=https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson
    curl -fsSLO $T/ne_110m_land.geojson
    curl -fsSLO $T/ne_110m_admin_0_boundary_lines_land.geojson
    utils/map_world.py ne_110m_land.geojson ne_110m_admin_0_boundary_lines_land.geojson \
        > gui_interface/web/map-world.js

Each ring or line is in tenths of a degree, the first point absolute and the
rest as differences, "lon,lat,dlon,dlat,..."; rings are separated by ";".

Copyright (C) 2026 Rhizomatica
SPDX-License-Identifier: GPL-3.0-or-later
"""
import json
import sys


def rings(path):
    for feature in json.load(open(path))["features"]:
        geom = feature["geometry"]
        coords = geom["coordinates"]
        if geom["type"] == "Polygon":
            yield from coords
        elif geom["type"] == "MultiPolygon":
            for polygon in coords:
                yield from polygon
        elif geom["type"] == "LineString":
            yield coords
        elif geom["type"] == "MultiLineString":
            yield from coords


def encode(path):
    out = []
    for ring in rings(path):
        pts = []
        for lon, lat in ring:
            p = (round(lon * 10), round(lat * 10))
            if not pts or p != pts[-1]:
                pts.append(p)
        if len(pts) < 2:
            continue
        nums = [pts[0][0], pts[0][1]]
        for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
            nums += [x1 - x0, y1 - y0]
        out.append(",".join(map(str, nums)))
    return ";".join(out)


land, borders = sys.argv[1:3]
print("// Generated by utils/map_world.py from Natural Earth 1:110m (public domain).")
print("// Land outlines and land borders in tenths of a degree, first point absolute,")
print("// then differences; \";\" between rings.")
print("var MAP_WORLD = {")
print('  land: "%s",' % encode(land))
print('  borders: "%s"' % encode(borders))
print("};")
