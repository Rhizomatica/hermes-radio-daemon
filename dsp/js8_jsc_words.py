#!/usr/bin/env python3
# Usage: dsp/js8_jsc_words.py <JS8Call-improved>/JS8_JSC/JSC_map.cpp dsp/js8_jsc_words.h
"""Extract JSC::map's words (index order) from JS8Call-improved's
JS8_JSC/JSC_map.cpp into dsp/js8_jsc_words.h: one string literal, the
words NUL-separated, in index order."""
import re, sys
src = open(sys.argv[1], encoding='latin-1').read()
s = src.index('const Tuple JSC::map[262144] = {')
e = src.index('};', s)
body = src[s + len('const Tuple JSC::map[262144] = {'):e]
body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
body = re.sub(r'//[^\n]*', '', body)
ents = re.findall(r'\{\s*"((?:[^"\\]|\\.)*)"\s*,\s*(\d+)\s*,\s*(\d+)\s*\}', body)
def unesc(x):
    out = []; i = 0
    while i < len(x):
        c = x[i]
        if c != '\\': out.append(c); i += 1; continue
        n = x[i+1]
        if n == 'x':
            j = i + 2
            while j < len(x) and x[j] in '0123456789abcdefABCDEF': j += 1
            out.append(chr(int(x[i+2:j], 16))); i = j
        else:
            out.append({'n': '\n', 't': '\t', '\\': '\\', '"': '"', "'": "'", '0': '\0'}[n]); i += 2
    return ''.join(out)
words = [None] * 262144
for w, size, idx in ents:
    words[int(idx)] = unesc(w)
missing = [i for i, w in enumerate(words) if w is None]
assert len(ents) == 262144 and not missing, (len(ents), missing[:5])
assert all('\0' not in w for w in words)
def lit(w):
    b = w.encode('latin-1')
    return ''.join(chr(c) if 32 <= c < 127 and chr(c) not in '"\\?' else '\\%03o' % c for c in b)
out = ['/* Generated by dsp/js8_jsc_words.py from JS8Call-improved JS8_JSC/JSC_map.cpp (GPL-3.0): JSC\'s',
       ' * 262144 words in index order, NUL-separated, Latin-1.  Do not edit. */',
       '#define JS8_JSC_WORDS 262144',
       'static const char js8_jsc_words[] =']
line = ''
for w in words:
    piece = lit(w) + '\\000'   # three digits: a following digit is not read into the escape
    if len(line) + len(piece) > 100:
        out.append('    "' + line + '"'); line = ''
    line += piece
out.append('    "' + line + '";')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print('words', len(words), 'bytes', sum(len(w.encode("latin-1")) + 1 for w in words))
print('samples', words[:8], words[68:73], words[10704:10708], words[-3:])
